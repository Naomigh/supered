from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = (root / 'edlib_origin/edlib/src/edlib.cpp').read_text()
first = source.index('static int myersCalcEditDistanceNW(')
start = source.index('static int myersCalcEditDistanceNW(', first + 1)
end = source.index('\n}\n', start) + 3
function = source[start:end].replace('myersCalcEditDistanceNW(', 'original_nw_preallocated(')
assert function.count('Block* blocks = new Block[maxNumBlocks];') == 1
function = function.replace('Block* blocks = new Block[maxNumBlocks];',
                            'Block stack_blocks[2];\n    Block* blocks = stack_blocks;')
function = function.replace('delete[] blocks;', '')
(root / 'generated/original_nw_preallocated.hpp').write_text(
    '// Generated by scripts/generate_original.py; only block storage allocation changes.\n' + function)
